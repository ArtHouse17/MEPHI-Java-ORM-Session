CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL CONSTRAINT uq_user_email UNIQUE,
    role VARCHAR(16) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN'))
);

CREATE TABLE user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES app_user(id) ON DELETE CASCADE,
    bio VARCHAR(2000),
    avatar_url VARCHAR(1000)
);

CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CONSTRAINT uq_category_name UNIQUE
);

CREATE TABLE tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL CONSTRAINT uq_tag_name UNIQUE
);

CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES category(id),
    teacher_id BIGINT NOT NULL REFERENCES app_user(id),
    start_date DATE NOT NULL,
    duration_weeks INTEGER NOT NULL CHECK (duration_weeks BETWEEN 1 AND 104)
);

CREATE TABLE course_tag (
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tag(id),
    PRIMARY KEY (course_id, tag_id)
);

CREATE TABLE course_module (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT uq_module_position UNIQUE (course_id, position)
);

CREATE TABLE lesson (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL REFERENCES course_module(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    content VARCHAR(12000) NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT uq_lesson_position UNIQUE (module_id, position)
);

CREATE TABLE lesson_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    location VARCHAR(500) NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE lesson_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    url VARCHAR(1000) NOT NULL
);

CREATE TABLE enrollment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES app_user(id),
    enrolled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_enrollment UNIQUE (course_id, student_id)
);

CREATE TABLE course_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES app_user(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_course_review UNIQUE (course_id, student_id)
);

CREATE TABLE assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(6000) NOT NULL,
    due_at TIMESTAMP WITH TIME ZONE NOT NULL,
    max_score INTEGER NOT NULL CHECK (max_score BETWEEN 1 AND 1000)
);

CREATE TABLE submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignment(id),
    student_id BIGINT NOT NULL REFERENCES app_user(id),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    content VARCHAR(10000) NOT NULL,
    score INTEGER CHECK (score >= 0),
    feedback VARCHAR(4000),
    CONSTRAINT uq_submission UNIQUE (assignment_id, student_id)
);

CREATE TABLE quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL CONSTRAINT uq_quiz_module UNIQUE REFERENCES course_module(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL
);

CREATE TABLE question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quiz(id) ON DELETE CASCADE,
    text VARCHAR(1200) NOT NULL,
    points INTEGER NOT NULL CHECK (points BETWEEN 1 AND 1000),
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT uq_question_position UNIQUE (quiz_id, position)
);

CREATE TABLE answer_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES question(id) ON DELETE CASCADE,
    text VARCHAR(600) NOT NULL,
    correct BOOLEAN NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT uq_option_position UNIQUE (question_id, position)
);

CREATE TABLE quiz_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quiz(id),
    student_id BIGINT NOT NULL REFERENCES app_user(id),
    taken_at TIMESTAMP WITH TIME ZONE NOT NULL,
    score INTEGER NOT NULL,
    max_score INTEGER NOT NULL,
    CONSTRAINT uq_quiz_submission UNIQUE (quiz_id, student_id),
    CHECK (max_score > 0 AND score BETWEEN 0 AND max_score)
);

CREATE TABLE quiz_answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES quiz_submission(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES question(id),
    selected_option_id BIGINT NOT NULL REFERENCES answer_option(id),
    points_awarded INTEGER NOT NULL CHECK (points_awarded >= 0),
    CONSTRAINT uq_quiz_answer UNIQUE (submission_id, question_id)
);

CREATE INDEX idx_course_category ON course(category_id);
CREATE INDEX idx_course_teacher ON course(teacher_id);
CREATE INDEX idx_course_tag_tag ON course_tag(tag_id);
CREATE INDEX idx_session_lesson_time ON lesson_session(lesson_id, starts_at);
CREATE INDEX idx_resource_lesson ON lesson_resource(lesson_id);
CREATE INDEX idx_enrollment_student ON enrollment(student_id);
CREATE INDEX idx_review_student ON course_review(student_id);
CREATE INDEX idx_assignment_lesson ON assignment(lesson_id);
CREATE INDEX idx_submission_student ON submission(student_id);
CREATE INDEX idx_quiz_submission_student ON quiz_submission(student_id);
CREATE INDEX idx_quiz_answer_question ON quiz_answer(question_id);
CREATE INDEX idx_quiz_answer_option ON quiz_answer(selected_option_id);
